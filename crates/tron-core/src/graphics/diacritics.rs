/// The number a placeholder diacritic encodes.
pub fn index(c: char) -> Option<u32> {
    DIACRITICS.binary_search_by_key(&u32::from(c), |&(cp, _)| cp).ok().map(|i| DIACRITICS[i].1)
}

#[cfg(test)]
mod tests {
    #[test]
    fn known_values() {
        assert_eq!(super::index('\u{305}'), Some(0));
        assert_eq!(super::index('\u{30D}'), Some(1));
        assert_eq!(super::index('a'), None);
    }
}
